print("[Lua] Analyzing multi-dimensional component registry...")

-- 1. 模拟复杂的结构化组件数据（可以包含多维数组、条件开关等）
local third_parties = {
  {
    name = "httplib",
    repoLink = "https://github.com/yhirose/cpp-httplib.git",
    version = "v0.45.0",
  },
  {
    name = "nlohmann_json",
    repoLink = "https://github.com/nlohmann/json.git",
