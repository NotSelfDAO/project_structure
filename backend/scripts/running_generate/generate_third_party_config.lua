# ========================================================
]],
  os.date("%Y-%m-%d %H:%M:%S")
))

file:flush()

for _, third_party in ipairs(third_parties) do
  print([[
[Lua] Generating target configuration for: ]] .. third_party.name
  )

  file:write(string.format([[
#Target: %s
handle_third_party(
    %s    
    %s    
    %s
)

]],
    third_party.name,
    third_party.name,
    third_party.repoLink,
    third_party.version
  ))
end

  file:flush()

file:close()

print([[
[Lua] Code generation complete: ]] .. output_path)