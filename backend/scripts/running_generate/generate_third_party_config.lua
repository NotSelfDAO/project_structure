  }
}

-- 2. 打开即将生成的临时 cmake 文件
local output_path = arg[1]
local file, err = io.open(output_path, "w")
if not file then error("Failed to write file: " .. tostring(err)) end

-- 3. 写入自动化生成的头部警告（防止别人手动误改）
file:write(string.format([[
